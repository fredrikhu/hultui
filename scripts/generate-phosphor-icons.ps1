#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Regenerates src/HultUI.Icons/Phosphor.Paths.g.cs from the @phosphor-icons/core package.

.DESCRIPTION
    Reads the icon list in scripts/phosphor-icons.txt, pulls each icon's `d` string out of
    the package's SVG assets, and writes the generated C# lookup table.

    The path data is copied verbatim — no rounding, no minification — so the bundled
    artwork is exactly upstream's. Only the wrapping into C# string literals is ours.

    A name ending in a weight suffix is taken from that weight's folder — `minus-bold` from
    assets/bold/, `circle-fill` from assets/fill/ — and everything else from regular. That
    matches the package's own file naming.

.PARAMETER Version
    The @phosphor-icons/core version to generate from. Recorded in the generated file's
    header, so a regeneration that changes artwork is visible in the diff.

.PARAMETER Assets
    An already-extracted assets directory (the one containing regular/ and bold/). When
    omitted the package is downloaded from the npm registry into a temp directory.

.PARAMETER Check
    Verify only: generate to memory and fail if the result differs from the file on disk.
    Nothing is written. Use this to confirm the checked-in file is reproducible.

.EXAMPLE
    ./scripts/generate-phosphor-icons.ps1
    ./scripts/generate-phosphor-icons.ps1 -Check
    ./scripts/generate-phosphor-icons.ps1 -Version 2.1.1 -Assets ~/phosphor/assets
#>
[CmdletBinding()]
param(
    [string]$Version = '2.1.1',
    [string]$Assets,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent $PSScriptRoot
$manifestPath = Join-Path $PSScriptRoot 'phosphor-icons.txt'
$outputPath = Join-Path $repo 'src/HultUI.Icons/Phosphor.Paths.g.cs'

# Emitted lines are indent + quote + content + `" +`, and the file is kept inside a
# reasonable column width. 110 characters of path data is what that leaves.
$ChunkBudget = 110
$Indent = '            '

function Get-Assets {
    param([string]$Version)

    $root = Join-Path ([IO.Path]::GetTempPath()) "phosphor-core-$Version"
    $assets = Join-Path $root 'package/assets'
    if (Test-Path $assets) {
        Write-Host "Using cached package at $root"
        return $assets
    }

    $url = "https://registry.npmjs.org/@phosphor-icons/core/-/core-$Version.tgz"
    $tgz = Join-Path ([IO.Path]::GetTempPath()) "phosphor-core-$Version.tgz"
    Write-Host "Downloading $url"
    Invoke-WebRequest $url -OutFile $tgz -TimeoutSec 300

    New-Item -ItemType Directory -Force $root | Out-Null
    tar -xzf $tgz -C $root
    if (-not (Test-Path $assets)) { throw "No assets directory in the package at $root" }
    return $assets
}

<#
    Splits path data before each command letter, then packs whole commands into chunks.
    Breaking mid-command would still compile and still draw the same picture, but it makes
    the generated file unreadable and every diff unreviewable.
#>
function Split-PathData {
    param([string]$Data, [int]$Budget)

    $tokens = [regex]::Matches($Data, '[MmLlHhVvCcSsQqTtAaZz][^MmLlHhVvCcSsQqTtAaZz]*')
    $chunks = @()
    $current = ''
    foreach ($t in $tokens) {
        $piece = $t.Value
        if ($current.Length -gt 0 -and ($current.Length + $piece.Length) -gt $Budget) {
            $chunks += $current
            $current = ''
        }
        $current += $piece
    }
    if ($current.Length -gt 0) { $chunks += $current }
    return $chunks
}

# ── Read the manifest ────────────────────────────────────────────────────────
if (-not (Test-Path $manifestPath)) { throw "Missing manifest: $manifestPath" }

$names = Get-Content $manifestPath |
    ForEach-Object { ($_ -replace '#.*$', '').Trim() } |
    Where-Object { $_.Length -gt 0 } |
    Sort-Object -Unique

if ($names.Count -eq 0) { throw "The manifest lists no icons" }

$assetsDir = if ($Assets) { $Assets } else { Get-Assets -Version $Version }

# ── Emit ─────────────────────────────────────────────────────────────────────
$sb = [Text.StringBuilder]::new()
[void]$sb.Append(@"
// <auto-generated>
//   Phosphor Icons (https://phosphoricons.com) - MIT licensed.
//   Generated from @phosphor-icons/core $Version by scripts/generate-phosphor-icons.ps1,
//   from the icon list in scripts/phosphor-icons.txt. One ``d`` string per icon, verbatim,
//   each in the set's native 256-unit box. Keys are the package's own asset names.
//
//   Regular weight throughout, plus the bold window-control marks: at caption-button size
//   the regular stroke is thinner than a device pixel and renders as a ghost.
//
//   Regenerate, do not edit.
// </auto-generated>

namespace HultUI.Icons;

public static partial class Phosphor
{
    /// <summary>The set's authoring box: every path below is in 256 x 256 units.</summary>
    public const float SourceBox = 256f;

    private static readonly Dictionary<string, string> Paths = new(StringComparer.OrdinalIgnoreCase)
    {
"@)

# The package stores each weight in its own folder and suffixes the file name to match.
# Regular is the exception: it carries no suffix.
$Weights = @('bold', 'duotone', 'fill', 'light', 'thin')

$missing = @()
foreach ($name in $names) {
    $weight = 'regular'
    foreach ($w in $Weights) { if ($name -like "*-$w") { $weight = $w; break } }
    $svgPath = Join-Path $assetsDir "$weight/$name.svg"
    if (-not (Test-Path $svgPath)) { $missing += "$name (expected $weight/$name.svg)"; continue }

    $svg = Get-Content $svgPath -Raw
    $paths = [regex]::Matches($svg, 'd="([^"]+)"')
    if ($paths.Count -eq 0) { $missing += "$name (no path data)"; continue }
    if ($paths.Count -gt 1) {
        # Every icon in the regular and bold weights is a single path. A multi-path asset
        # would silently lose everything after the first, so refuse it instead.
        $missing += "$name (multi-path asset; this generator emits one path per icon)"
        continue
    }

    # @() matters: a path short enough to need no wrapping comes back as a bare string,
    # and indexing a string yields characters — every such icon emitted just "M".
    $chunks = @(Split-PathData -Data $paths[0].Groups[1].Value -Budget $ChunkBudget)
    [void]$sb.Append("`n        [`"$name`"] =")
    for ($i = 0; $i -lt $chunks.Count; $i++) {
        $tail = if ($i -eq $chunks.Count - 1) { ',' } else { ' +' }
        [void]$sb.Append("`n$Indent`"$($chunks[$i])`"$tail")
    }
}

if ($missing.Count -gt 0) {
    throw "Not found in @phosphor-icons/core ${Version}:`n  " + ($missing -join "`n  ")
}

[void]$sb.Append("`n    };`n}`n")
$generated = $sb.ToString() -replace "`r`n", "`n"

# ── Write or check ───────────────────────────────────────────────────────────
if ($Check) {
    $existing = if (Test-Path $outputPath) { [IO.File]::ReadAllText($outputPath) -replace "`r`n", "`n" } else { '' }
    if ($existing -ne $generated) {
        $tmp = Join-Path ([IO.Path]::GetTempPath()) 'Phosphor.Paths.g.expected.cs'
        [IO.File]::WriteAllText($tmp, $generated)
        throw "$outputPath is not what the manifest generates. Expected output written to $tmp"
    }
    Write-Host "OK: $($names.Count) icons, generated output matches the checked-in file."
    return
}

[IO.File]::WriteAllText($outputPath, $generated)
Write-Host "Wrote $($names.Count) icons to $outputPath (from @phosphor-icons/core $Version)."
