#!/usr/bin/env python3
"""Generates src/HultUI.WebView.Cef/Interop/DomCodes.g.cs: for every key on the USB HID
keyboard page, its XKB keycode (what CEF's native_key_code wants on Linux, and what fills a
page's KeyboardEvent.code) and its DOM code name, from Chromium's own table
(ui/events/keycodes/dom/dom_code_data.inc) at the CEF's Chromium release.

SDL's scancodes are the USB HID usages, so HultUI's KeyDownEvent.ScanCode (seam W6) indexes
this table directly. Spike L0 question 5 found native_key_code to be the XKB keycode.

    python3 scripts/generate-cef-keys.py [--chromium 146.0.7680.177] [--file dom_code_data.inc]
"""
import argparse, base64, os, re, urllib.request

ap = argparse.ArgumentParser()
ap.add_argument("--chromium", default="146.0.7680.177")
ap.add_argument("--file", help="a local copy of dom_code_data.inc instead of fetching it")
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src",
                                            "HultUI.WebView.Cef", "Interop", "DomCodes.g.cs"))
args = ap.parse_args()

if args.file:
    text = open(args.file).read()
else:
    url = (f"https://chromium.googlesource.com/chromium/src/+/refs/tags/{args.chromium}/"
           "ui/events/keycodes/dom/dom_code_data.inc?format=TEXT")
    text = base64.b64decode(urllib.request.urlopen(url).read()).decode()

rows = {}
for m in re.finditer(r'DOM_CODE\(0x([0-9a-f]+),\s*0x([0-9a-f]+),\s*0x([0-9a-f]+),\s*0x([0-9a-f]+),\s*0x([0-9a-f]+),\s*("([^"]*)"|nullptr),', text):
    usb, xkb, code = int(m.group(1), 16), int(m.group(3), 16), m.group(7)
    if usb >> 16 == 0x07 and code and xkb:
        rows[usb & 0xFFFF] = (xkb, code)

lines = [
    f"// <auto-generated> by scripts/generate-cef-keys.py from Chromium {args.chromium}'s",
    "// ui/events/keycodes/dom/dom_code_data.inc. Do not edit. </auto-generated>",
    "#nullable enable",
    "namespace HultUI.WebView.Cef.Interop;",
    "",
    "/// <summary>The USB HID keyboard page (SDL's scancodes): each key's XKB keycode and DOM code.</summary>",
    "internal static class DomCodes",
    "{",
    "    /// <summary>The XKB keycode of a keyboard-page usage, or 0.</summary>",
    "    public static int Xkb(int usage) => usage switch",
    "    {",
]
for usage, (xkb, code) in sorted(rows.items()):
    lines.append(f"        0x{usage:04x} => 0x{xkb:04x},   // {code}")
lines += ["        _ => 0,", "    };", "",
          "    /// <summary>The DOM code (KeyboardEvent.code) of a keyboard-page usage, or null.</summary>",
          "    public static string? Code(int usage) => usage switch", "    {"]
for usage, (xkb, code) in sorted(rows.items()):
    lines.append(f"        0x{usage:04x} => \"{code}\",")
lines += ["        _ => null,", "    };", "",
          "    /// <summary>The keyboard-page usage of a DOM code, or 0.</summary>",
          "    public static int Usage(string code) => code switch", "    {"]
for usage, (xkb, code) in sorted(rows.items(), key=lambda r: r[1][1]):
    lines.append(f"        \"{code}\" => 0x{usage:04x},")
lines += ["        _ => 0,", "    };", "}", ""]
with open(args.out, "w") as f:
    f.write("\n".join(lines))
print(f"{len(rows)} keys -> {os.path.normpath(args.out)}")
